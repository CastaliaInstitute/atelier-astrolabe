uint16_t blend565(uint16_t fg, uint16_t bg, uint8_t alpha) {
  if (alpha == 0) return bg;
  if (alpha == 255) return fg;
  const uint8_t fr = ((fg >> 11) & 0x1F) * 255 / 31;
  const uint8_t fg_g = ((fg >> 5) & 0x3F) * 255 / 63;
  const uint8_t fb = (fg & 0x1F) * 255 / 31;
  const uint8_t br = ((bg >> 11) & 0x1F) * 255 / 31;
  const uint8_t bg_g = ((bg >> 5) & 0x3F) * 255 / 63;
  const uint8_t bb = (bg & 0x1F) * 255 / 31;
  const uint16_t ia = 255u - alpha;
  const uint8_t r = static_cast<uint8_t>((fr * alpha + br * ia) / 255u);
  const uint8_t g = static_cast<uint8_t>((fg_g * alpha + bg_g * ia) / 255u);
  const uint8_t b = static_cast<uint8_t>((fb * alpha + bb * ia) / 255u);
  return static_cast<uint16_t>(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3));
}

